// Captura o livro de receitas e o cardápio com modo de preparo (v2.3), em 375 px e com dados fictícios.
// Uso: node scripts/capturar-v2-3.mjs [url]; padrão http://localhost:4365/ (npm run preview)
import { chromium } from '@playwright/test'
const navegador = await chromium.launch()
const pagina = await (await navegador.newContext({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 2 })).newPage()
await pagina.clock.install({ time: new Date(2026, 10, 10, 11, 0, 0) })
await pagina.goto(process.argv[2] ?? 'http://localhost:4365/')
await pagina.getByLabel('Peso de hoje (kg)').fill('60,5')
await pagina.getByLabel('Meta de peso (kg)').fill('70')
await pagina.getByLabel('Altura (cm)').fill('175')
await pagina.getByLabel('Idade').fill('30')
await pagina.getByRole('button', { name: 'Continuar' }).click()
await pagina.getByRole('button', { name: 'Continuar' }).click()
await pagina.getByRole('button', { name: 'Começar' }).click()
await pagina.getByText('DIA 1 DE 365').waitFor()
const foto = (nome, inteira = false) => pagina.screenshot({ path: `docs/capturas/${process.env.PREFIXO ?? "v2-3"}-${nome}.png`, fullPage: inteira })

await pagina.getByRole('navigation').getByRole('button', { name: 'Cardápio' }).click()
const almoco = pagina.locator('details.refeicao').nth(3)
await almoco.locator('summary').click()
await almoco.scrollIntoViewIfNeeded()
await pagina.evaluate(() => window.scrollBy(0, -60))
await foto('dia-com-preparo')

await pagina.getByRole('tab', { name: 'Receitas' }).click()
await pagina.locator('.livro-conta').waitFor()
await foto('livro')
await pagina.getByLabel('Refeição').selectOption({ label: 'Jantar' })
await pagina.getByLabel('Tipo').selectOption({ label: 'Besteira planejada' })
await pagina.locator('details.receita').filter({ hasText: 'Nuggets' }).locator('summary').first().click()
await pagina.locator('details.receita[open]').scrollIntoViewIfNeeded()
await pagina.evaluate(() => window.scrollBy(0, -20))
await foto('receita-besteira')
await pagina.getByLabel('Refeição').selectOption({ label: 'Todas' })
await pagina.getByLabel('Tipo').selectOption({ label: 'Todos' })
await pagina.getByLabel('Buscar receita').fill('tapioca')
await pagina.evaluate(() => window.scrollTo(0, 0))
await foto('busca')
await navegador.close()
console.log('capturas da v2.3 salvas em docs/capturas')

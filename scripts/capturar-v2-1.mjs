// Captura a tela Hoje com o dia ajustado (v2.1), em 375 px e com dados fictícios. Rodar com o app em http://localhost:5365.
import { chromium } from '@playwright/test'
const navegador = await chromium.launch()
const pagina = await (await navegador.newContext({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 2 })).newPage()
await pagina.clock.install({ time: new Date(2026, 10, 9, 6, 40, 0) })
await pagina.goto(process.argv[2] ?? 'http://localhost:5365/')
await pagina.getByLabel('Peso de hoje (kg)').fill('60,5')
await pagina.getByLabel('Meta de peso (kg)').fill('70')
await pagina.getByLabel('Altura (cm)').fill('175')
await pagina.getByLabel('Idade').fill('30')
await pagina.getByRole('button', { name: 'Continuar' }).click()
await pagina.screenshot({ path: 'docs/capturas/v2-1-rotina.png', fullPage: true })
await pagina.getByRole('button', { name: 'Continuar' }).click()
await pagina.getByRole('button', { name: 'Começar' }).click()
await pagina.getByRole('button', { name: 'FEITO' }).click()
await pagina.getByLabel('Horário do dia').waitFor()
await pagina.waitForTimeout(900)
await pagina.screenshot({ path: 'docs/capturas/v2-1-hoje-ajustado.png', fullPage: true })
await navegador.close()
console.log('capturas da v2.1 salvas em docs/capturas')

// Captura as telas da etapa 3 em 375 px. Rodar com o app em http://localhost:5365 (npm run dev).
import { chromium } from '@playwright/test'

const URL = process.argv[2] ?? 'http://localhost:5365/'
const navegador = await chromium.launch()
const contexto = await navegador.newContext({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 2 })
const pagina = await contexto.newPage()
await pagina.clock.install({ time: new Date(2026, 10, 9, 10, 0, 0) })
const foto = (nome, inteira = true) => pagina.screenshot({ path: `docs/capturas/${nome}.png`, fullPage: inteira })

await pagina.goto(URL)
await pagina.getByLabel('Peso de hoje (kg)').fill('60,5')
await pagina.getByLabel('Meta de peso (kg)').fill('70')
await pagina.getByLabel('Altura (cm)').fill('175')
await pagina.getByLabel('Idade').fill('30')
await pagina.getByRole('button', { name: 'Continuar' }).click()
await pagina.getByLabel('Acordo às', { exact: true }).fill('05:30')
await pagina.getByLabel('Termino o trabalho às').fill('18:18')
await pagina.getByLabel('Chego em casa às').fill('21:30')
await pagina.getByRole('button', { name: 'Continuar' }).click()
await pagina.getByRole('button', { name: 'Começar' }).click()
await pagina.getByText('DIA 1 DE 365').waitFor()
await foto('etapa3-hoje-com-prato', false)
await pagina.getByRole('button', { name: 'Cardápio' }).click()
await pagina.locator('details.refeicao').first().waitFor()
await foto('etapa3-cardapio-dia')
await pagina.getByRole('tab', { name: 'Semana' }).click()
await pagina.locator('article.marmita').first().waitFor()
await foto('etapa3-semana')
await pagina.getByRole('tab', { name: 'Receitas' }).click()
await pagina.locator('details').first().locator('summary').click()
await foto('etapa3-receitas')
await pagina.getByRole('tab', { name: 'Compras' }).click()
await pagina.getByLabel(/Arroz cru/).check()
await foto('etapa3-compras')
await navegador.close()
console.log('capturas da etapa 3 salvas em docs/capturas')

// Captura as telas da v2.2 (aquecimento, passo a passo, troca na hora e alongamento) em 375 px, com dados fictícios.
// Uso: node scripts/capturar-v2-2.mjs [url]; padrão http://localhost:5365/
import { chromium } from '@playwright/test'
const navegador = await chromium.launch()
const pagina = await (await navegador.newContext({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 2 })).newPage()
await pagina.clock.install({ time: new Date(2026, 10, 9, 6, 15, 0) })
await pagina.goto(process.argv[2] ?? 'http://localhost:5365/')
await pagina.getByLabel('Peso de hoje (kg)').fill('60,5')
await pagina.getByLabel('Meta de peso (kg)').fill('70')
await pagina.getByLabel('Altura (cm)').fill('175')
await pagina.getByLabel('Idade').fill('30')
await pagina.getByRole('button', { name: 'Continuar' }).click()
await pagina.getByRole('button', { name: 'Continuar' }).click()
await pagina.getByRole('button', { name: 'Começar' }).click()
await pagina.getByText('DIA 1 DE 365').waitFor()
const foto = (nome) => pagina.screenshot({ path: `docs/capturas/v2-2-${nome}.png` })

await pagina.getByRole('navigation').getByRole('button', { name: 'Treino' }).click()
await pagina.getByRole('button', { name: 'COMEÇAR TREINO' }).click()
await pagina.getByRole('dialog', { name: 'Aquecimento' }).waitFor()
await foto('aquecimento-lista')
await pagina.getByRole('button', { name: 'Começar', exact: true }).click()
await pagina.clock.runFor(41_000)
await foto('aquecimento-movimento')
await pagina.getByRole('button', { name: 'Pular aquecimento' }).click()

await pagina.locator('details.passo-a-passo').waitFor()
await pagina.locator('.exec-corpo').evaluate((e) => e.scrollTo(0, 120))
await foto('passo-a-passo')
await pagina.locator('details.passo-a-passo summary').click()
const trocar = pagina.getByLabel('Trocar exercício')
const opcao = (await trocar.locator('option').allTextContents())[1]
await trocar.selectOption({ label: opcao })
await pagina.locator('.exec-corpo').evaluate((e) => e.scrollTo(0, 0))
await foto('troca')

await pagina.getByRole('button', { name: 'Registrar série' }).click()
await pagina.getByRole('button', { name: 'Pular descanso' }).click()
await pagina.getByRole('button', { name: 'Concluir treino antes do fim' }).click()
await pagina.getByRole('button', { name: 'Concluir agora' }).click()
await pagina.getByRole('dialog', { name: 'Alongamento' }).waitFor()
await pagina.getByRole('button', { name: 'Começar', exact: true }).click()
await pagina.clock.runFor(20_000)
await foto('alongamento')
await navegador.close()
console.log('capturas da v2.2 salvas em docs/capturas')
